import { test, expect } from "bun:test";
import { join } from "node:path";
import { writeFileSync, readFileSync } from "node:fs";
import { orch, seedHome, tempDir, fakeBin, editJson, readJson, readText, autoCleanup } from "../helpers";
autoCleanup();

test("schedule edit", () => {
  const home = seedHome();
  const sh = fakeBin({ claude: 'printf "ran\\n"' });
  const o = orch(home, { PATH: `${sh}:${process.env.PATH}` });
  const se = (...a: string[]) => o("schedule", ...a);
  const cid = se("add", "--name", "echoer", "--cron", "0 9 * * *", "--command", "echo one").out.trim();
  expect(cid).toMatch(/^sch-/);
  const cfile = join(home, "schedules", cid, "schedule.json");
  const s = () => readJson(cfile);
  const created = s().created_at;
  editJson(cfile, (x) => { x.runs = [{ started_at: "2026-01-01T00:00:00Z", ended_at: "2026-01-01T00:00:01Z", kind: "command", ref: "/x", status: "ok", exit: 0 }]; x.last_run_at = "2026-01-01T00:00:00Z"; });
  let r = se("edit", cid, "--name", "renamed");
  expect(r.rc).toBe(0); expect(r.all).toContain(`edited: ${cid}`);
  expect([s().name, s().created_at, s().runs.length, s().last_run_at]).toEqual(["renamed", created, 1, "2026-01-01T00:00:00Z"]);
  expect(s().updated_at).toMatch(/^20[0-9-]+T/);
  const oldNext = s().next_at;
  editJson(cfile, (x) => { x.next_at = 1000; });
  expect(se("edit", cid, "--name", "renamed-again", "--cron", "0 9 * * *").rc).toBe(0);
  expect(s().next_at).toBe(1000);
  editJson(cfile, (x) => { x.next_at = oldNext; });
  expect(se("edit", cid, "--cron", "30 14 * * *").rc).toBe(0);
  expect(s().cron).toBe("30 14 * * *");
  expect(s().next_at).not.toBe(oldNext);
  const d = new Date(s().next_at * 1000);
  expect(`${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`).toBe("14:30");
  const before = readText(cfile);
  r = se("edit", cid, "--cron", "61 * * * *");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/bad or never-matching cron/);
  expect(readText(cfile)).toBe(before);
  const wd = tempDir();
  expect(se("edit", cid, "--command", "echo two", "--workdir", wd, "--timeout", "5m").rc).toBe(0);
  expect([s().command, s().workdir, s().timeout]).toEqual(["echo two", wd, 300]);
  expect(se("edit", cid, "--workdir", "/no/such/dir").rc).toBe(2);
  expect(se("edit", cid, "--timeout", "soon").rc).toBe(2);
  se("edit", cid, "--workdir", "");
  expect(s().workdir ?? null).toBeNull();
  se("disable", cid); se("edit", cid, "--name", "paused-one");
  expect([s().enabled, s().next_at ?? null]).toEqual([false, null]);
  se("enable", cid);
  expect(se("edit", cid, "--prompt", "hi").rc).toBe(2);
  expect(se("edit", cid, "--prompt", "hi", "--profile", "no-such-profile").rc).toBe(2);
  expect(se("edit", cid, "--profile", "claude-default").rc).toBe(2);
  expect(se("edit", cid, "--prompt", "say hi", "--profile", "claude-default").rc).toBe(0);
  const k = s();
  expect([k.kind, k.prompt, k.profile, k.command ?? null, k.workdir ?? null, k.timeout ?? 0]).toEqual(["prompt", "say hi", "claude-default", null, null, 0]);
  expect(s().runs.length).toBe(1);
  writeFileSync(join(wd, "p.md"), "from a file\n");
  se("edit", cid, "--prompt", `@${join(wd, "p.md")}`);
  expect([s().prompt.trim(), s().profile]).toEqual(["from a file", "claude-default"]);
  editJson(join(home, "profiles.json"), (p) => { p.profiles["claude-default"].allowed_models = ["claude-sonnet", "claude-opus"]; });
  expect(se("edit", cid, "--model", "claude-opus").rc).toBe(0);
  expect([s().model, s().prompt.trim()]).toEqual(["claude-opus", "from a file"]);
  expect(se("edit", cid, "--model", "claude-haiku").rc).toBe(2);
  expect(s().model).toBe("claude-opus");
  se("edit", cid, "--model", "");
  expect(s().model ?? null).toBeNull();
  se("edit", cid, "--model", "claude-opus"); se("edit", cid, "--profile", "claude-default");
  expect(s().model).toBe("claude-opus");
  editJson(join(home, "profiles.json"), (p) => { p.profiles["claude-default"].allowed_models = ["claude-sonnet"]; });
  se("edit", cid, "--profile", "claude-default");
  expect(s().model ?? null).toBeNull();
  editJson(join(home, "profiles.json"), (p) => { p.profiles["claude-default"].allowed_models = ["claude-sonnet", "claude-opus"]; });
  se("edit", cid, "--model", "claude-opus");
  expect(se("edit", cid, "--timeout", "5m").rc).toBe(2);
  se("edit", cid, "--command", "echo back");
  expect([s().kind, s().command, s().prompt ?? null, s().profile ?? null, s().model ?? null]).toEqual(["command", "echo back", null, null, null]);
  expect(se("edit", cid, "--model", "claude-opus").rc).toBe(2);
  expect(se("edit", cid, "--prompt", "a", "--command", "b").rc).toBe(2);
  expect(se("edit", cid).rc).toBe(2);
  expect(se("edit", cid, "--bogus", "x").rc).toBe(2);
  expect(se("edit", cid, "--name").rc).toBe(2);
  r = se("edit", "sch-20200101-000000-abcd", "--name", "x");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/^unknown schedule/m);
  expect(s().id).toBe(cid);
});
