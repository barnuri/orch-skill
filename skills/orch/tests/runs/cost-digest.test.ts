import { test, expect } from "bun:test";
import { join } from "node:path";
import { existsSync, mkdirSync, statSync, writeFileSync } from "node:fs";
import { orch, seedHome, runState, readText, fakeBin, runCmd, DISPATCH, cleanEnv, autoCleanup } from "../helpers";
autoCleanup();

const SUCCESS = '{"result":"the answer","total_cost_usd":0.2409,"is_error":false,"usage":{"input_tokens":2,"output_tokens":4,"cache_read_input_tokens":81324,"cache_creation_input_tokens":19861},"modelUsage":{"claude-opus-5[1m]":{"inputTokens":2,"outputTokens":4,"cacheReadInputTokens":81324,"cacheCreationInputTokens":19861,"costUSD":0.2394,"costBasis":"list"}}}';
const claudeShim = (payload: string, exit = 0) => fakeBin({ claude: `cat <<'PAYLOAD'\n${payload}\nPAYLOAD\nexit ${exit}` });

test("claude json cost sidecar", () => {
  const home = seedHome();
  const withClaude = (payload: string, exit = 0) => orch(home, { PATH: `${claudeShim(payload, exit)}:${process.env.PATH}` });
  let o = withClaude(SUCCESS);
  let r = o("run", "claude", "hi");
  expect(r.rc).toBe(0);
  expect(r.all).toMatch(/^the answer$/m);
  expect(r.all).not.toMatch(/total_cost_usd/);
  const job = o("start", "claude", "hi").out.trim();
  expect(job).toMatch(/^[0-9]/);
  o("wait", job, "--timeout", "30", "--interval", "0.1");
  expect(existsSync(join(home, "jobs", job, "usage.json"))).toBe(true);
  const usage = readText(join(home, "jobs", job, "usage.json"));
  for (const m of [/"usd":0\.2409/, /"cost_basis":"list"/, /"input_tokens":2/, /"cache_creation_tokens":19861/, /"model":"claude-opus-5\[1m\]"/]) expect(usage).toMatch(m);
  expect(readText(join(home, "jobs", job, "log"))).toMatch(/^the answer$/m);
  r = withClaude('{"result":"nope","is_error":true,"total_cost_usd":0.01}')("run", "claude", "hi");
  expect(r.rc).toBe(1); expect(r.all).toMatch(/^nope$/m);
  r = withClaude("not json at all")("run", "claude", "hi");
  expect(r.rc).toBe(0); expect(r.all).toMatch(/^not json at all$/m);
  r = withClaude("boom", 3)("run", "claude", "hi");
  expect(r.rc).toBe(3);
});

test("node cost", () => {
  const home = seedHome(), o = orch(home);
  const R = o("run", "start", "cost run").out.trim();
  o("node", "add", R, "n1", "first");
  const cost = () => runState(home, R).nodes[0].cost ?? null;
  expect(cost()).toBeNull();
  let r = o("node", "cost");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/dispatch\.ts node cost/);
  r = o("node", "cost", R, "n1");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/pass --from-job or --clear/);
  expect(o("node", "cost", R, "n1", "--bogus").rc).toBe(2);
  expect(o("node", "cost", R, "n1", "--from-job").rc).toBe(2);
  expect(o("node", "cost", R, "nope", "--from-job", "j1").rc).toBe(2);
  r = o("node", "cost", R, "n1", "--from-job", "missing-job");
  expect(r.rc).toBe(1); expect(r.all).toMatch(/recorded no usage/);
  mkdirSync(join(home, "jobs/costjob"), { recursive: true });
  writeFileSync(join(home, "jobs/costjob/usage.json"), '{"usd":0.2409,"cost_basis":"list","input_tokens":2,"output_tokens":4,"cache_read_tokens":81324,"cache_creation_tokens":19861,"models":[{"model":"claude-opus-5[1m]","usd":0.2394,"input_tokens":2,"output_tokens":4,"cache_read_tokens":81324,"cache_creation_tokens":19861}]}');
  expect(o("node", "cost", R, "n1", "--from-job", "costjob").rc).toBe(0);
  expect([cost().usd, cost().cost_basis, cost().models[0].model]).toEqual([0.2409, "list", "claude-opus-5[1m]"]);
  expect(o("node", "cost", R, "n1", "--clear").rc).toBe(0);
  expect(cost()).toBeNull();
  expect(o("node", "cost", R, "n1", "--from-job", "costjob", "--clear").rc).toBe(2);
  writeFileSync(join(home, "jobs/costjob/usage.json"), "not json\n");
  o("node", "cost", R, "n1", "--from-job", "costjob");
  expect(cost()).toBeNull();
  const sh = claudeShim('{"result":"done","total_cost_usd":0.5,"is_error":false,"usage":{"input_tokens":7,"output_tokens":9,"cache_read_input_tokens":0,"cache_creation_input_tokens":0},"modelUsage":{"m1":{"inputTokens":7,"outputTokens":9,"costUSD":0.5,"costBasis":"list"}}}');
  const oc = orch(home, { PATH: `${sh}:${process.env.PATH}` });
  const sj = oc("node", "dispatch", R, "n1", "claude", "hi").out.trim();
  oc("wait", sj, "--timeout", "30", "--interval", "0.1");
  o("run", "sync", R);
  expect(cost().usd).toBe(0.5);
  // A job that exits 0 without a handoff is an error (no handoff = not done).
  expect(runState(home, R).nodes[0].status).toBe("error");
});

test("node out and digest", () => {
  const home = seedHome(), o = orch(home);
  const R = o("run", "start", "handoff run").out.trim();
  o("node", "add", R, "impl", "Implement"); o("node", "add", R, "review", "Review", "--after", "impl");
  let r = o("node", "out");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/dispatch\.ts node out/);
  expect(o("node", "out", R, "impl", "extra").rc).toBe(2);
  expect(o("node", "out", "nosuchrun", "impl").rc).toBe(2);
  expect(o("node", "out", R, "nosuchnode").rc).toBe(2);
  expect(o("node", "out", R, "../escape").rc).toBe(2);
  r = o("node", "out", R, "impl");
  expect(r.rc).toBe(0);
  const implOut = r.out.trim();
  expect(implOut).toMatch(new RegExp(`runs/${R}/out/impl$`));
  expect(statSync(implOut).isDirectory()).toBe(true);
  expect(o("node", "out", R, "impl").out.trim()).toBe(implOut);
  r = o("node", "digest", R, "impl");
  expect(r.rc).toBe(0);
  expect(r.out).toMatch(/^node: impl \(waiting\)$/m);
  expect(r.out).toContain(`out: ${implOut}`);
  expect(r.out).toMatch(/^log: not dispatched$/m);
  expect(o("node", "digest", R, "impl", "--lines", "0").rc).toBe(2);
  expect(o("node", "digest", R, "impl", "--lines", "9999").rc).toBe(2);
  expect(o("node", "digest", R, "impl", "--bogus").rc).toBe(2);
  const sh = fakeBin({ claude: `printf 'ORCH_NODE_OUT=%s\\n' "\${ORCH_NODE_OUT:-unset}"\nprintf 'ORCH_RUN_ID=%s\\n' "\${ORCH_RUN_ID:-unset}"\nprintf 'ORCH_NODE_ID=%s\\n' "\${ORCH_NODE_ID:-unset}"\ni=0\nwhile [ "$i" -lt 200 ]; do printf 'line %s\\n' "$i"; i=$((i + 1)); done` });
  const oc = orch(home, { PATH: `${sh}:${process.env.PATH}` });
  const job = oc("node", "dispatch", R, "impl", "claude", "go").out.trim();
  oc("wait", job, "--timeout", "30", "--interval", "0.1");
  const log = readText(join(home, "jobs", job, "log"));
  expect(log).toContain(`ORCH_NODE_OUT=${implOut}`);
  expect(log).toContain(`ORCH_RUN_ID=${R}`);
  expect(log).toMatch(/ORCH_NODE_ID=impl/);
  r = o("node", "digest", R, "impl");
  expect(r.rc).toBe(0);
  expect(r.out).toContain(`job: ${job}`);
  expect(r.out).toMatch(/^exit: 0$/m);
  expect(r.out).toMatch(/^log: \d+ bytes, \d+ lines$/m);
  expect(r.out).toMatch(/^--- first 10 ---$/m);
  expect(r.out).toMatch(/^--- last 10 ---$/m);
  expect(r.out).toMatch(/^--- \d+ lines elided ---$/m);
  expect(r.out).toMatch(/^ORCH_NODE_OUT=/m);
  expect(r.out).toMatch(/^line 199$/m);
  expect(r.out).not.toMatch(/^line 100$/m);
  expect(r.out.split("\n").length - 1).toBeLessThan(40);
  r = o("node", "digest", R, "impl", "--lines", "200");
  expect(r.all).not.toMatch(/lines elided/);
  expect(r.out).toMatch(/^line 100$/m);
});

test("artifact", () => {
  const home = seedHome(), o = orch(home);
  let r = o("artifact");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/dispatch\.ts artifact <run-id>/);
  r = o("artifact", "r1", "r2");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/one run id at a time/);
  r = o("artifact", "r1", "--bogus");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/unknown flag --bogus/);
  expect(o("artifact", "r1", "--out").rc).toBe(2);
  expect(o("artifact", "r1").rc).toBe(1);
  const id = o("run", "start", "snapshot me").out.trim();
  o("node", "add", id, "n1", "first node");
  const emit = join(home, "emitted");
  r = o("artifact", id, "--out", emit);
  expect(r.rc).toBe(0);
  expect(existsSync(join(emit, "index.html"))).toBe(true);
  expect(r.all).toMatch(/embedded document/);
  const html = readText(join(emit, "index.html"));
  expect(html).toContain(`orch-island-run-${id}`);
  expect(html).toMatch(/orch-island-runs/);
  expect(html).not.toMatch(/orch-island-health/);
  expect(html).toMatch(/src="\.\/chunk-/);
  expect(html).not.toMatch(/(src|href)="https?:\/\//);
  expect(o("artifact", id).rc).toBe(0);
  expect(existsSync(join(home, "artifacts", id, "index.html"))).toBe(true);
  r = o("artifact", "20260101-000000-ffff", "--out", join(home, "nope"));
  expect(r.rc).toBe(1); expect(r.all).toMatch(/no run 20260101-000000-ffff/);
}, 120000);
