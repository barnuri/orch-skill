import { test, expect } from "bun:test";
import { join } from "node:path";
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { orch, seedHome, runState, nodeOf, autoCleanup } from "../helpers";
autoCleanup();

test("carry a run", () => {
  const home = seedHome(), o = orch(home);
  const R = o("run", "start", "carry demo").out.trim();
  o("node", "add", R, "a", "Finished"); o("node", "add", R, "b", "Running", "--after", "a", "--profile", "claude-default");
  o("node", "add", R, "c", "Waiting on b", "--after", "b"); o("node", "add", R, "d", "Independent");
  o("node", "add", R, "e", "Failed"); o("node", "add", R, "f", "Skipped on purpose");
  o("node", "update", R, "a", "running"); o("node", "update", R, "a", "done");
  o("node", "update", R, "b", "running", "--job", "job-123", "--force");
  o("node", "update", R, "e", "running"); o("node", "update", R, "e", "error", "--error", "boom");
  o("node", "update", R, "f", "skipped");
  const outB = o("node", "out", R, "b").out.trim();
  writeFileSync(join(outB, "handoff.md"), "partial\n");
  const strip = (n: any) => { const { out_dir, ...x } = n; return JSON.stringify(x, Object.keys(x).sort()); };
  const beforeB = strip(nodeOf(home, R, "b"));
  const rr = o("run", "carry", R);
  expect(rr.rc).toBe(0);
  const N = rr.out.trim();
  expect(N).toMatch(/^\d{8}-\d{6}-[0-9a-f]{4}$/);
  const s = runState(home, N);
  expect(s.nodes.map((n: any) => n.id).join(" ")).toBe("b c d e");
  expect(nodeOf(home, N, "b").status).toBe("running");
  expect(strip(nodeOf(home, N, "b"))).toBe(beforeB);
  expect(nodeOf(home, N, "b").job_id).toBe("job-123");
  expect([nodeOf(home, N, "e").status, nodeOf(home, N, "e").error]).toEqual(["error", "boom"]);
  expect(nodeOf(home, N, "c").status).toBe("waiting");
  expect(s.edges.map((e: string[]) => e.join(">")).join(",")).toBe("b>c");
  expect(s.edges.some((e: string[]) => e[0] === "a")).toBe(false);
  expect(s.continued_from).toBe(R);
  const old = runState(home, R);
  expect(old.continued_to).toBe(N);
  expect(nodeOf(home, R, "a").status).toBe("done");
  expect(nodeOf(home, R, "b").error).toBe(`moved to run ${N}`);
  expect(old.status).toBe("done");
  expect(readFileSync(join(outB, "handoff.md"), "utf8").trim()).toBe("partial");
  expect(o("node", "out", N, "b").out.trim()).toBe(outB);
  expect(o("node", "out", N, "d").out.trim()).toMatch(new RegExp(`/runs/${N}/out/d$`));
  expect(o("run", "sync", N).all).toMatch(/^b\s+error$/m);
  let r = o("run", "carry", R);
  expect(r.rc).toBe(0); expect(r.all).toMatch(/nothing to carry/);
  expect(o("run", "carry", "no-such-run").rc).toBe(2);
  expect(o("run", "carry").rc).toBe(2);
  expect(o("run", "carry", N, "--nope").rc).toBe(2);
  const R2 = o("run", "start", "keep open demo").out.trim(); o("node", "add", R2, "x", "waiting");
  const N2 = o("run", "carry", R2, "--keep-open", "--title", "renamed").out.trim();
  expect(runState(home, R2).status).toBe("running");
  expect(runState(home, N2).title).toBe("renamed");
  const R3 = o("run", "start", "keep skipped demo").out.trim(); o("node", "add", R3, "y", "skipped one"); o("node", "update", R3, "y", "skipped");
  const N3 = o("run", "carry", R3, "--keep-skipped").out.trim();
  expect(runState(home, N3).nodes.map((n: any) => n.id).join(",")).toBe("y");
});

test("carry on fixtures", () => {
  const home = seedHome(), o = orch(home);
  const fixture = (id: string, nodes: any[], edges: any[]) => {
    mkdirSync(join(home, "runs", id), { recursive: true });
    writeFileSync(join(home, "runs", id, "state.json"), JSON.stringify({ run_id: id, title: "Old", started: "2026-01-01T00:00:00Z", finished: null, status: "running", nodes, edges }));
  };
  expect(o("run", "carry").rc).toBe(2);
  expect(o("run", "carry", "r1", "--bogus").rc).toBe(2);
  expect(o("run", "carry", "nope").rc).toBe(2);
  fixture("fin", [{ id: "a", status: "done" }, { id: "s", status: "skipped" }], []);
  const before = readdirSync(join(home, "runs")).join(",");
  let r = o("run", "carry", "fin");
  expect(r.rc).toBe(0); expect(r.all).toMatch(/nothing to carry: all 2 node/);
  expect(readdirSync(join(home, "runs")).join(",")).toBe(before);
  fixture("r1", [{ id: "a", status: "done" }, { id: "b", status: "running", job_id: "j1" }, { id: "c", status: "waiting" }], [["a", "b"], ["b", "c"]]);
  mkdirSync(join(home, "runs/r1/out/b"), { recursive: true });
  r = o("run", "carry", "r1", "--id", "r2", "--title", "Next");
  expect(r.rc).toBe(0); expect(r.out.trim()).toBe("r2");
  const n = runState(home, "r2");
  expect(`${n.title} ${n.nodes.map((x: any) => x.id).join(",")} ${JSON.stringify(n.edges)} ${n.continued_from}`).toBe('Next b,c [["b","c"]] r1');
  const b = n.nodes.find((x: any) => x.id === "b");
  expect([b.job_id, b.out_dir]).toEqual(["j1", join(home, "runs/r1/out/b")]);
  expect(n.nodes.find((x: any) => x.id === "c").out_dir ?? null).toBeNull();
  const old = runState(home, "r1");
  expect(`${old.status} ${old.continued_to} ${old.nodes.map((x: any) => x.status).join(",")}`).toBe("done r2 done,skipped,skipped");
});
