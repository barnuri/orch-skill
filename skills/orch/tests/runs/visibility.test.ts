import { test, expect } from "bun:test";
import { join } from "node:path";
import { mkdirSync, writeFileSync } from "node:fs";
import { orch, seedHome, runState, nodeOf, readText, readJson, writeJson, editJson, ndjson, waitUntil, runCmdAsync, DISPATCH, autoCleanup } from "../helpers";
autoCleanup();
const mk = () => { const home = seedHome(); return { home, o: orch(home, { ORCH_WAIT_POLL_SECS: "1" }) }; };
const L = (...rows: object[]) => ndjson(rows);

test("ping, notes, events", () => {
  const { home, o } = mk();
  const R = o("run", "start", "visibility demo").out.trim();
  o("node", "add", R, "a", "Alpha"); o("node", "add", R, "b", "Beta", "--after", "a"); o("node", "add", R, "c", "Gamma");
  expect(runState(home, R).nodes[0].created).toMatch(/^20/);
  o("node", "update", R, "a", "running");
  expect(o("node", "ping", R, "a", "--note", "reading files", "--progress", "1/4").rc).toBe(0);
  let a = nodeOf(home, R, "a");
  expect(a.progress).toBe("1/4");
  expect(a.notes.at(-1).text).toBe("reading files");
  for (let i = 1; i <= 25; i++) o("node", "ping", R, "a", "--note", `n${i}`);
  a = nodeOf(home, R, "a");
  expect(a.notes.length).toBe(20);
  expect(a.notes.at(-1).text).toBe("n25");
  expect(o("node", "ping", R, "a", "--bogus").rc).toBe(2);
  o("node", "report", R, "a", "--note", "reported");
  expect(nodeOf(home, R, "a").updated).toMatch(/^20/);
  const ev = readText(join(home, "runs", R, "events.jsonl"));
  expect(ev).toMatch(/"kind":"status".*"to":"running"/);
  expect(ev).toMatch(/"kind":"note".*"note":"n25"/);
  expect(o("node", "ping", R).rc).toBe(2);
});

test("backfill, --at, stale, status, wait", async () => {
  const { home, o } = mk();
  const R = o("run", "start", "visibility demo").out.trim();
  o.in(L({ op: "add", id: "a", label: "Alpha" }, { op: "add", id: "b", label: "Beta", after: "a" }, { op: "add", id: "c", label: "Gamma" }, { op: "update", id: "a", status: "running" }), "node", "batch", R);
  o("node", "update", R, "c", "done");
  const nodes = () => runState(home, R).nodes;
  expect(nodes()[2].backfilled).toBe(true);
  expect(nodes()[2].started).toMatch(/^20/);
  expect(nodes()[0].backfilled ?? false).toBe(false);
  expect(o("node", "update", R, "a", "done", "--at", "2099-01-01T00:00:00Z").rc).toBe(2);
  expect(o("node", "update", R, "a", "done", "--at", "yesterday").rc).toBe(2);
  o("node", "update", R, "a", "done", "--at", "2026-01-02T03:04:05Z");
  expect(nodes()[0].finished).toBe("2026-01-02T03:04:05Z");
  o("node", "add", R, "s", "Silent"); o("node", "update", R, "s", "running");
  editJson(join(home, "runs", R, "state.json"), (st) => { const n = st.nodes.find((x: any) => x.id === "s"); n.started = n.updated = "2020-01-01T00:00:00Z"; });
  expect(o("run", "sync", R, "--no-retry").out).toMatch(/^stale: s$/m);
  o("node", "ping", R, "s", "--note", "alive");
  expect(o("run", "sync", R, "--no-retry").out).not.toMatch(/^stale:/m);
  const st = o("run", "status", R).out;
  expect(st).toMatch(/visibility demo \[running\] 2\/4 done/);
  expect(st).toMatch(/running s:/);
  expect(st).toMatch(/^http:\/\/127\.0\.0\.1:\d+\/#\/run\//m);
  expect(o("run", "status", R, "--json").out).toMatch(/"done": ?2/);
  const waiter = (async () => { await waitUntil(() => readText(join(home, "runs", R, "wait.cursor")) !== "", 20); await runCmdAsync(["bun", DISPATCH, "node", "update", R, "s", "done"], { home }); })();
  const w = await runCmdAsync(["bun", DISPATCH, "run", "wait", R, "--timeout", "20"], { home, env: { ORCH_WAIT_POLL_SECS: "1" } }).then((x) => ({ rc: x.rc, out: x.out }));
  await waiter;
  expect(w.rc).toBe(0);
  expect(w.out).toMatch(/^s running->done \[unknown\]$/m);
  const R2 = o("run", "start", "wait timeout").out.trim();
  o("node", "add", R2, "x", "X"); o("node", "update", R2, "x", "running");
  expect(o("run", "wait", R2, "--timeout", "2").rc).toBe(124);
  o("node", "update", R2, "x", "done");
  expect(o("run", "wait", R2, "--timeout", "5").rc).toBe(0);
  expect(o("run", "wait", R2, "--timeout", "5").rc).toBe(3);
}, 120000);

test("ownership and transitions", () => {
  const { home, o } = mk();
  const RO = o("run", "start", "ownership").out.trim();
  o.in(L({ op: "add", id: "u", label: "Unowned" }, { op: "add", id: "w", label: "Owned" }, { op: "update", id: "u", status: "running" }), "node", "batch", RO);
  o("node", "update", RO, "w", "running", "--owner", "coordinator");
  expect(nodeOf(home, RO, "w").owner).toBe("coordinator");
  expect(o("run", "sync", RO, "--no-retry").out).toMatch(/^unowned: u$/m);
  expect(o("run", "status", RO).out).toMatch(/running u:.*UNOWNED/);
  expect(o("run", "status", RO).out).toMatch(/running w: [^U]*$/m);
  mkdirSync(join(home, "jobs/job-9"), { recursive: true });
  o("node", "add", RO, "j", "Job");
  o("node", "update", RO, "j", "running", "--job", "job-9");
  expect(nodeOf(home, RO, "j").owner).toBe("job-9");

  const RT = o("run", "start", "transitions").out.trim();
  o.in(L({ op: "add", id: "t", label: "T" }, { op: "update", id: "t", status: "running", owner: "coordinator" }, { op: "update", id: "t", status: "error", error: "boom" }), "node", "batch", RT);
  expect(o("node", "update", RT, "t", "waiting").rc).toBe(0);
  const t = nodeOf(home, RT, "t");
  expect([t.started, t.finished, t.error, t.owner, t.job_id].map((x) => x ?? null)).toEqual([null, null, null, null, null]);
  expect(t.attempts.at(-1).error).toBe("boom");
  o("node", "update", RT, "t", "running", "--owner", "coordinator"); o("node", "update", RT, "t", "done");
  const r = o("node", "update", RT, "t", "running");
  expect(r.rc).toBe(2);
  expect(r.all).toMatch(/can move to: nothing/);
  expect(o("node", "update", RT, "t", "waiting").rc).toBe(2);
  expect(o("node", "update", RT, "t", "waiting", "--force").rc).toBe(0);
  expect(readText(join(home, "runs", RT, "events.jsonl"))).toMatch(/"from":"done","to":"waiting"/);
  o("node", "update", RT, "t", "skipped");
  expect(o("node", "update", RT, "t", "done").all).toMatch(/can move to: waiting running/);
  const j = o("node", "update", RT, "t", "running", "--job", "nope");
  expect(j.rc).toBe(2);
  expect(j.all).toMatch(/job nope not found/);
});

test("carry origin deps, remove, unowned chain", () => {
  const { home, o } = mk();
  const RC = o("run", "start", "origin").out.trim();
  o.in(L({ op: "add", id: "fin", label: "Finished" }, { op: "update", id: "fin", status: "running", owner: "coordinator" }, { op: "update", id: "fin", status: "done" }, { op: "add", id: "open", label: "Open" }), "node", "batch", RC);
  o("run", "carry", RC);
  const N = Bun.spawnSync(["sh", "-c", `grep -l '"continued_from": "${RC}"' "${home}"/runs/*/state.json | head -1`]).stdout.toString().trim().split("/").slice(-2)[0];
  const add = o("node", "add", N, "later", "Later", "--after", "fin");
  expect(add.rc).toBe(0);
  expect(add.err).toMatch(`dependency fin is finished in run ${RC}`);
  expect(runState(home, N).edges.filter((e: string[]) => e[1] === "later").length).toBe(0);
  const bad = o("node", "add", N, "bad", "Bad", "--after", "ghost");
  expect(bad.rc).toBe(2);
  expect(bad.all).toMatch(`searched: ${N} ${RC}`);

  const RR = o("run", "start", "remove").out.trim();
  o.in(L({ op: "add", id: "p", label: "P" }, { op: "add", id: "q", label: "Q", after: "p" }, { op: "add", id: "r", label: "R" }), "node", "batch", RR);
  expect(o("node", "remove", RR, "r").rc).toBe(0);
  expect(runState(home, RR).nodes.length).toBe(2);
  o("node", "update", RR, "p", "running", "--owner", "coordinator");
  expect(o("node", "remove", RR, "p").rc).toBe(2);
  o("node", "update", RR, "p", "done"); o("node", "update", RR, "q", "running", "--owner", "coordinator");
  expect(o("node", "remove", RR, "p").rc).toBe(2);
  expect(o("node", "remove", RR, "p", "--force").rc).toBe(0);
  expect(runState(home, RR).edges.length).toBe(0);
  expect(readText(join(home, "runs", RR, "events.jsonl"))).toMatch(/"kind":"remove"/);

  // r1 chained to r0
  mkdirSync(join(home, "runs/r0"), { recursive: true }); mkdirSync(join(home, "runs/r1"), { recursive: true });
  mkdirSync(join(home, "jobs/job-1"), { recursive: true }); writeFileSync(join(home, "jobs/job-1/pid"), `${process.pid}\n`);
  writeJson(join(home, "runs/r0/state.json"), { run_id: "r0", title: "origin", status: "done", edges: [], nodes: [{ id: "z", status: "done" }] });
  writeJson(join(home, "runs/r1/state.json"), { run_id: "r1", title: "t", status: "running", continued_from: "r0", edges: [["a", "b"], ["w", "x"]],
    nodes: [{ id: "a", status: "waiting" }, { id: "b", status: "running", owner: "job-1", job_id: "job-1" }, { id: "u", status: "running" }, { id: "w", status: "waiting" }, { id: "x", status: "waiting" }, { id: "d", status: "done" }] });
  expect(o("run", "sync", "r1", "--no-retry").out).toMatch(/^unowned: u$/m);
  const od = o("node", "add", "r1", "k", "K", "--after", "z");
  expect(od.err).toMatch(/finished in run r0/);
  let r = o("node", "remove", "r1", "d");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/is done/);
  r = o("node", "remove", "r1", "a");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/dependents: b/);
  expect(o("node", "remove", "r1", "w", "--bogus").rc).toBe(2);
  expect(o("node", "remove", "r1", "w").rc).toBe(0);
  const s = runState(home, "r1");
  expect([s.nodes.some((n: any) => n.id === "w"), s.edges.length]).toEqual([false, 1]);
  const last = readText(join(home, "runs/r1/events.jsonl")).trim().split("\n").pop()!;
  const ev = JSON.parse(last);
  expect([ev.kind, ev.node, ev.from, ev.to ?? null]).toEqual(["remove", "w", "waiting", null]);
  expect(o("node", "ping", "r1", "b", "--bogus").rc).toBe(2);
  expect(o("node", "ping", "r1").rc).toBe(2);
});
