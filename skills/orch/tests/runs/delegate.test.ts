import { test, expect } from "bun:test";
import { join } from "node:path";
import { writeFileSync } from "node:fs";
import { orch, seedHome, editJson, runState, autoCleanup } from "../helpers";
autoCleanup();

test("delegate plan, tasks, findings", () => {
  const home = seedHome(), o = orch(home);
  editJson(join(home, "profiles.json"), (p) => { p.profiles["claude-default"].quality = "high"; p.profiles["local-llm-fast"].quality = "standard"; });
  o("run", "start", "Delegated", "--id", "del-1");
  const d = () => runState(home, "del-1").delegation;
  const D = (...a: string[]) => o("delegate", "del-1", ...a);
  let out = D("show").all;
  expect(out).toMatch(/^plan:$/m);
  expect(out).toMatch(/^ {2}\(none\)$/m);
  expect(D("show", "--json").all).toMatch(/"tasks":\[\]/);
  expect(D("plan", "Split the auth refactor into three parts").out).toMatch(/^plan stored$/m);
  expect(d().plan).toMatch(/^Split the auth refactor/);
  writeFileSync(join(home, "plan.md"), "Plan from file");
  D("plan", `@${join(home, "plan.md")}`);
  expect(d().plan).toBe("Plan from file");
  expect(D("plan", `@${join(home, "missing.md")}`).rc).toBe(2);
  expect(D("task", "add", "plan-1", "--stage", "plan", "--profile", "claude-default", "--label", "Plan it").out).toMatch(/^task plan-1 added$/m);
  D("task", "add", "impl-1", "--stage", "implement", "--profile", "local-llm-fast", "--label", "Build it");
  D("task", "add", "rev-1", "--stage", "review", "--profile", "claude-default");
  D("task", "add", "fix-1", "--stage", "fix", "--profile", "local-llm-fast");
  expect(D("show").out).toMatch(/^ {2}impl-1\timplement\tlocal-llm-fast\ttodo\tBuild it$/m);
  let r = D("task", "add", "bad-1", "--stage", "plan", "--profile", "local-llm-fast");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/stage plan needs a strong profile/);
  r = D("task", "add", "bad-2", "--stage", "implement", "--profile", "claude-default");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/stage implement needs a cheap profile/);
  expect(D("task", "add", "bad-3", "--stage", "review", "--profile", "local-llm-fast").rc).toBe(2);
  expect(D("task", "add", "bad-4", "--stage", "build", "--profile", "claude-default").rc).toBe(2);
  expect(D("task", "add", "bad-5", "--stage", "implement", "--profile", "no-such").all).toMatch(/unknown profile no-such/);
  expect(D("task", "add", "impl-1", "--stage", "implement", "--profile", "local-llm-fast").all).toMatch(/task impl-1 already exists/);
  expect(d().tasks.length).toBe(4);
  expect(D("task", "set", "impl-1", "done").out).toMatch(/^task impl-1 done$/m);
  expect(d().tasks.find((t: any) => t.id === "impl-1").status).toBe("done");
  expect(D("task", "set", "impl-1", "finished").rc).toBe(2);
  expect(D("task", "set", "nope", "todo").all).toMatch(/unknown task nope/);
  expect(D("finding", "add", "rev-1", "Token is logged in plain text").out.trim()).toBe("F1");
  D("finding", "add", "rev-1", "Missing timeout on the refresh call");
  expect(D("show").out).toMatch(/^ {2}F1\trev-1\tToken is logged in plain text$/m);
  expect(D("show").out).toMatch(/^open findings: 2$/m);
  expect(D("finding", "close", "F1").out).toMatch(/^finding F1 closed$/m);
  expect(D("show").out).toMatch(/^open findings: 1$/m);
  expect(D("finding", "add", "nope", "x").all).toMatch(/unknown task nope/);
  expect(D("finding", "close", "F9").all).toMatch(/unknown finding F9/);
  expect(o("delegate", "nope-run", "show").rc).toBe(2);
  expect(o("delegate", "del-1").rc).toBe(2);
});
