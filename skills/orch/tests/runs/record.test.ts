import { test, expect } from "bun:test";
import { orch, seedHome, nodeOf, autoCleanup } from "../helpers";
autoCleanup();

test("model, timestamps, report", async () => {
  const home = seedHome(), o = orch(home);
  const R = o("run", "start", "record test").out.trim().split("\n").pop()!;
  const nd = (id: string) => nodeOf(home, R, id);
  o("node", "add", R, "a", "first", "--model", "claude-opus-5-5"); o("node", "add", R, "b", "second", "--after", "a");
  expect(nd("a").model).toBe("claude-opus-5-5");
  expect(nd("b").model ?? null).toBeNull();
  expect(nd("a").started ?? null).toBeNull();
  const before = Date.now() / 1000;
  o("node", "update", R, "a", "running");
  const started = nd("a").started;
  expect(started).toMatch(/^\d{4}-\d{2}-\d{2}T[0-9:]{8}Z$/);
  expect(nd("a").finished ?? null).toBeNull();
  const se = Date.parse(started) / 1000;
  expect(se).toBeGreaterThanOrEqual(before - 1);
  expect(se).toBeLessThanOrEqual(Date.now() / 1000 + 1);
  await Bun.sleep(1100);
  o("node", "update", R, "a", "done");
  const fin = nd("a").finished;
  expect(fin).toMatch(/^\d{4}-\d{2}-\d{2}T[0-9:]{8}Z$/);
  expect(fin > started).toBe(true);
  o("node", "update", R, "b", "running"); o("node", "update", R, "b", "error", "--error", "boom");
  expect(nd("b").finished).toMatch(/^20/);
  expect(o("node", "report", R, "a", "--model", "claude-opus-5-5", "--input-tokens", "1200", "--output-tokens", "300", "--cache-read-tokens", "5000", "--usd", "0.42", "--note", "inline").rc).toBe(0);
  const rep = nd("a").report;
  expect([rep.model, rep.input_tokens, rep.output_tokens, rep.cache_read_tokens, rep.usd, rep.reported_by, rep.note]).toEqual(["claude-opus-5-5", 1200, 300, 5000, 0.42, "inline", "inline"]);
  o("node", "report", R, "b", "--model", "claude-haiku-4-5");
  expect([nd("b").report.usd ?? null, nd("b").report.input_tokens ?? null, nd("b").model, nd("b").cost ?? null]).toEqual([null, null, "claude-haiku-4-5", null]);
  o("node", "report", R, "b", "--usd", "0.01", "--note", "just cost");
  expect(nd("b").model).toBe("claude-haiku-4-5");
  const r1 = o("node", "report", R, "a");
  expect(r1.rc).toBe(2); expect(r1.all).toMatch(/nothing to record/);
  expect(o("node", "report", R, "a", "--input-tokens", "abc").rc).toBe(2);
  expect(o("node", "report", R, "a", "--usd", "-1").rc).toBe(2);
  expect(o("node", "report", R, "nope", "--usd", "1").rc).toBe(2);
  expect(o("node", "report", R, "a", "--bogus").rc).toBe(2);
  const sync = o("run", "sync", R).all;
  expect(sync).toMatch(/reported: a inline model=claude-opus-5-5 in=1200 out=300 usd=0.42/);
  expect(sync).toMatch(/reported: b inline model=claude-haiku-4-5 in=- out=- usd=0.01/);
  expect(o("node", "digest", R, "a").all).toMatch(/reported: inline model=claude-opus-5-5/);
});
