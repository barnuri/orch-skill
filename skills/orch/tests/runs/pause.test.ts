import { test, expect } from "bun:test";
import { join } from "node:path";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { orch, seedHome, runState, nodeOf, pidAlive, waitUntil, autoCleanup } from "../helpers";
autoCleanup();

test("pause, resume, cancel", async () => {
  const home = seedHome(), o = orch(home);
  const st = () => runState(home, "pause-1");
  const nd = (id: string) => nodeOf(home, "pause-1", id);
  o("run", "start", "Pause test", "--id", "pause-1");
  for (const [n, g] of [["dead", "dies on restart"], ["live", "keeps running"], ["later", "not started yet"]]) o("node", "add", "pause-1", n, g);
  const deadJob = o("node", "dispatch", "pause-1", "dead", "claude-native", "do dead", "--flag", "x").out.trim();
  const liveJob = o("node", "dispatch", "pause-1", "live", "claude-native", "do live").out.trim();
  o("wait", deadJob, "--timeout", "60", "--interval", "1"); o("wait", liveJob, "--timeout", "60", "--interval", "1");
  const deadSession = nd("dead").session;
  expect(deadSession).toBeTruthy();
  const live = Bun.spawn(["sleep", "120"]);
  writeFileSync(join(home, "jobs", liveJob, "pid"), `${live.pid}\n`);
  expect(o("run", "pause", "pause-1").rc).toBe(0);
  expect([st().paused, st().auto_resume]).toEqual([true, true]);
  expect(o("run", "status", "pause-1").out).toMatch(/^paused: true$/m);
  let r = o("run", "sync", "pause-1");
  expect(r.all).toMatch(/run paused/); expect(r.rc).toBe(0);
  expect(nd("dead").status).toBe("running");
  r = o("node", "dispatch", "pause-1", "later", "claude-native", "go");
  expect(r.all).toMatch(/run paused/); expect(r.rc).toBe(3);
  expect(nd("later").status).toBe("waiting");
  r = o("run", "resume", "pause-1");
  expect(r.rc).toBe(0);
  expect([st().paused, st().auto_resume]).toEqual([false, false]);
  expect(o("run", "status", "pause-1").out).not.toMatch(/^paused: true$/m);
  expect(r.out).toMatch(new RegExp(`^alive: live ${liveJob}$`, "m"));
  expect(r.out).toMatch(/^redispatched: dead /m);
  const newJob = nd("dead").job_id;
  expect(newJob).not.toBe(deadJob);
  expect(nd("dead").status).toBe("running");
  expect(readFileSync(join(home, "jobs", newJob, "session"), "utf8").trim()).toBe(deadSession);
  expect(nd("dead").dispatch_args).toEqual(["--flag", "x"]);
  expect(nd("live").job_id).toBe(liveJob);
  expect(nd("live").status).toBe("running");
  const job = o("node", "dispatch", "pause-1", "later", "claude-native", "go");
  expect(job.rc).toBe(0);
  expect(nd("later").status).toBe("running");

  const cancel = { pid: Number(Bun.spawnSync(["sh", "-c", "sleep 300 >/dev/null 2>&1 </dev/null & echo \$!"]).stdout.toString().trim()) };
  mkdirSync(join(home, "jobs/cancel-job"), { recursive: true });
  writeFileSync(join(home, "jobs/cancel-job/pid"), `${cancel.pid}\n`);
  o("node", "add", "pause-1", "cancel-me", "to cancel");
  o("node", "update", "pause-1", "cancel-me", "running", "--job", "cancel-job");
  r = o("node", "cancel", "pause-1", "cancel-me");
  expect(r.rc).toBe(0);
  expect(r.out).toMatch(/^cancelled: cancel-me \(job killed\)$/m);
  expect(nd("cancel-me").status).toBe("stopped");
  expect(await waitUntil(() => !pidAlive(cancel.pid), 10)).toBe(true);
  expect(nd("live").status).toBe("running");
  expect(st().stopped ?? false).toBe(false);
  expect(o("node", "retry", "pause-1", "cancel-me", "--no-dispatch").rc).toBe(0);
  expect(nd("cancel-me").status).toBe("waiting");
  expect(o("node", "cancel", "pause-1", "cancel-me").rc).toBe(3);
  live.kill();
  o("wait", newJob, "--timeout", "60", "--interval", "1");
  o("wait", job.out.trim(), "--timeout", "60", "--interval", "1");
}, 240000);

test("pause/resume/stop/set on a plain run", () => {
  const home = seedHome(), o = orch(home);
  const st = () => runState(home, "r1");
  mkdirSync(join(home, "runs/r1"), { recursive: true });
  writeFileSync(join(home, "runs/r1/state.json"), JSON.stringify({ run_id: "r1", title: "t", status: "running", edges: [], nodes: [{ id: "a", status: "waiting" }, { id: "b", status: "done" }] }));
  let r = o("run", "pause", "r1");
  expect(r.rc).toBe(0); expect(r.out).toMatch(/^paused: r1$/m);
  expect([st().paused, st().auto_resume, st().paused_at != null]).toEqual([true, true, true]);
  r = o("run", "sync", "r1");
  expect(r.all).toMatch(/run paused: r1/);
  r = o("run", "resume", "r1");
  expect(r.rc).toBe(0); expect(r.out).toMatch(/^resumed: r1$/m);
  expect([st().paused, st().auto_resume, st().paused_at ?? null, st().stopped]).toEqual([false, false, null, false]);
  r = o("run", "stop", "r1");
  expect(r.rc).toBe(0); expect(r.all).toMatch(/killed 0 job/);
  expect([st().stopped, st().auto_resume]).toEqual([true, false]);
  expect(o("run", "sync", "r1").all).toMatch(/run stopped: r1/);
  expect(o("run", "resume", "r1").rc).toBe(3);
  expect(o("run", "resume", "r1", "--stopped").rc).toBe(0);
  expect(st().stopped).toBe(false);
  expect(o("run", "pause").rc).toBe(2);
  expect(o("run", "pause", "r1", "extra").rc).toBe(2);
  expect(o("run", "resume", "r1", "--bogus").rc).toBe(2);
  expect(o("run", "pause", "nope").rc).toBe(2);
  expect(o("run", "set", "r1", "colour", "red").rc).toBe(2);
  expect(o("run", "set", "r1", "auto_dispatch", "maybe").rc).toBe(2);
  o("run", "set", "r1", "auto_dispatch", "true");
  expect(st().auto_dispatch).toBe(true);
  expect(o("node", "cancel", "r1", "a").rc).toBe(3);
});
