import { test, expect } from "bun:test";
import { join } from "node:path";
import { orch, seedHome, runState, nodeOf, fakeBin, pidAlive, readText, autoCleanup } from "../helpers";
import { readFileSync } from "node:fs";
autoCleanup();

test("run stop and resume --stopped", () => {
  const home = seedHome();
  const shim = fakeBin({ claude: "sleep 60" });
  const o = orch(home, { PATH: `${shim}:${process.env.PATH}` });
  const st = () => runState(home, "stop-1");
  const nd = (id: string) => nodeOf(home, "stop-1", id);
  o("run", "start", "Stop test", "--id", "stop-1");
  o("node", "add", "stop-1", "live", "runs long"); o("node", "add", "stop-1", "later", "not started yet");
  const liveJob = o("node", "dispatch", "stop-1", "live", "claude", "do live").out.trim();
  const pid = Number(readFileSync(join(home, "jobs", liveJob, "pid"), "utf8").trim());
  expect(pid).toBeGreaterThan(0);
  let r = o("run", "stop", "stop-1");
  expect(r.rc).toBe(0);
  expect(r.out).toMatch(/^stopped: stop-1 \(killed 1 job\(s\)\)$/m);
  expect(pidAlive(pid)).toBe(false);
  expect([st().stopped, st().auto_resume]).toEqual([true, false]);
  expect(nd("live").status).toBe("stopped");
  expect(nd("later").status).toBe("waiting");
  expect(st().status).not.toBe("cancelled");
  expect(o("run", "status", "stop-1").out).toMatch(/^stopped: true$/m);
  r = o("run", "sync", "stop-1");
  expect(r.all).toMatch(/run stopped/);
  expect(r.rc).toBe(0);
  expect(nd("live").status).toBe("stopped");
  expect(o("node", "dispatch", "stop-1", "later", "claude", "go").rc).toBe(3);
  expect(nd("later").status).toBe("waiting");
  r = o("run", "resume", "stop-1");
  expect(r.rc).toBe(3);
  expect(r.all).toMatch(/--stopped/);
  expect(st().stopped).toBe(true);
  expect(o("run", "resume", "stop-1", "--bogus").rc).toBe(2);
  r = o("run", "resume", "stop-1", "--stopped");
  expect(r.rc).toBe(0);
  expect(st().stopped).toBe(false);
  expect(r.all).toMatch(/^redispatched: live /m);
  expect(nd("live").job_id).not.toBe(liveJob);
  expect(nd("live").status).toBe("running");
  expect(o("run", "status", "stop-1").out).not.toMatch(/^stopped: true$/m);
  expect(o("run", "stop").rc).toBe(2);
  expect(o("run", "stop", "no-such-run").rc).toBe(2);
  o("run", "stop", "stop-1");
});
