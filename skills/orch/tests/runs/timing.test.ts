import { test, expect } from "bun:test";
import { join } from "node:path";
import { mkdirSync, writeFileSync } from "node:fs";
import { orch, seedHome, runState, nodeOf, editJson, readText, autoCleanup } from "../helpers";
autoCleanup();

test("dispatch/start segments, pauses, backfill", () => {
  const home = seedHome(), o = orch(home);
  const nd = (id: string, run = "time-1") => nodeOf(home, run, id);
  o("run", "start", "Timing test", "--id", "time-1");
  o("node", "add", "time-1", "a", "timed node"); o("node", "add", "time-1", "b", "stopped node");
  const job = o("node", "dispatch", "time-1", "a", "claude-native", "do a").out.trim();
  expect(nd("a").status).toBe("running");
  expect(nd("a").dispatched_at).not.toBeNull();
  expect(nd("a").started_at ?? null).toBeNull();
  expect(nd("a").seg_open).toBe(true);
  expect(nd("a").started).toMatch(/^20/);
  o("node", "ping", "time-1", "a", "--progress", "1/3");
  const first = nd("a").started_at;
  expect(first).toMatch(/^20[0-9-]+T/);
  expect(readText(join(home, "runs/time-1/events.jsonl")).split("\n").filter((l) => l.includes('"node":"a"')).join("\n")).toMatch(/"kind":"started"/);
  Bun.sleepSync(1000);
  o("node", "ping", "time-1", "a", "--progress", "2/3");
  expect(nd("a").started_at).toBe(first);
  expect(o("node", "started", "time-1", "a", "--at", "2000-01-01T00:00:00Z").rc).toBe(0);
  expect(nd("a").started_at).toBe(first);
  o("wait", job, "--timeout", "60", "--interval", "1");
  o("node", "update", "time-1", "a", "error", "--error", "process died");
  expect(nd("a").finished_at).not.toBeNull();
  expect(nd("a").seg_open).toBe(false);
  expect(nd("a").run_segments.length).toBe(1);
  expect(nd("a").run_segments[0].start).toBe(first);
  o("node", "retry", "time-1", "a", "--no-dispatch");
  const job2 = o("node", "dispatch", "time-1", "a", "claude-native", "do a again").out.trim();
  expect(nd("a").started_at ?? null).toBeNull();
  expect(nd("a").run_segments.length).toBe(1);
  o("owner", "event", job2, "started", "--harness", "test");
  expect(nd("a").started_at).toMatch(/^20[0-9-]+T/);
  o("wait", job2, "--timeout", "60", "--interval", "1");
  o("node", "update", "time-1", "a", "done");
  expect(nd("a").run_segments.length).toBe(2);
  const job3 = o("node", "dispatch", "time-1", "b", "claude-native", "do b").out.trim();
  o("node", "started", "time-1", "b", "--source", "test");
  o("wait", job3, "--timeout", "60", "--interval", "1");
  o("run", "stop", "time-1");
  expect([nd("b").status, nd("b").seg_open, nd("b").run_segments.length]).toEqual(["stopped", false, 1]);
  Bun.sleepSync(1000);
  o("run", "resume", "time-1", "--stopped");
  const s = runState(home, "time-1");
  expect(s.pauses.length).toBe(1);
  expect(s.pauses[0].from < s.pauses[0].to).toBe(true);

  o("run", "start", "Legacy", "--id", "legacy-1");
  o("node", "add", "legacy-1", "old", "legacy node"); o("node", "add", "legacy-1", "nolog", "legacy node without evidence");
  mkdirSync(join(home, "jobs/job-old"), { recursive: true });
  writeFileSync(join(home, "jobs/job-old/log"), "hello\n");
  editJson(join(home, "runs/legacy-1/state.json"), (st) => {
    st.nodes = st.nodes.map((n: any) => { const m = { ...n, status: "done", started: "2026-01-01T00:00:00Z", finished: "2030-01-01T00:00:00Z", job_id: n.id === "old" ? "job-old" : "job-none" }; for (const k of ["dispatched_at", "started_at", "finished_at", "run_segments", "seg_open"]) delete m[k]; return m; });
  });
  const out = o("run", "backfill-timing", "legacy-1");
  expect(out.rc).toBe(0);
  expect(out.all).toMatch(/legacy-1 2 node/);
  expect(nd("old", "legacy-1").dispatched_at).toBe("2026-01-01T00:00:00Z");
  expect(nd("old", "legacy-1").started_at).not.toBeNull();
  expect(nd("nolog", "legacy-1").started_at ?? null).toBeNull();
  expect(nd("nolog", "legacy-1").finished_at).toBe("2030-01-01T00:00:00Z");
  expect(nd("nolog", "legacy-1").run_segments.length).toBe(1);
  expect(o("run", "backfill-timing", "legacy-1").all).toMatch(/legacy-1 0 node/);
}, 240000);
