import { test, expect } from "bun:test";
import { join } from "node:path";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { orch, seedHome, tempDir, fakeBin, fakeHerdrBin, readJson, readText, runState, waitUntil, pathWithout, autoCleanup } from "../helpers";
autoCleanup();

const setup = () => {
  const root = tempDir();
  const fake = fakeHerdrBin();
  const shims = fakeBin({ claude: `printf 'shim HOME=%s marker=%s\\n' "$HOME" "\${ORCH_TEST_MARKER:-none}"\n[ -z "\${ORCH_TEST_SLEEP:-}" ] || sleep "$ORCH_TEST_SLEEP"\nexit "\${ORCH_TEST_EXIT:-0}"` });
  const realhome = join(root, "realhome"), home = join(root, "orch home"), webdir = join(root, "envs.d"), log = join(root, "herdr-calls.log");
  mkdirSync(realhome, { recursive: true }); mkdirSync(home, { recursive: true }); writeFileSync(log, "");
  const env = { HOME: realhome, PATH: `${fake}:${shims}:${process.env.PATH}`, ORCH_HERDR: "1", ORCH_HERDR_FAKE_LOG: log, ORCH_HERDR_CLOSE_AFTER: "1", ORCH_HERDR_START_WAIT: "8", ORCH_HERDR_CALL_TIMEOUT: "40",
    ORCH_HERDR_WEB_ENVS_DIR: webdir, HERDR_SOCKET_PATH: join(realhome, "live-session.sock"), HERDR_ENV: "1", HERDR_PANE_ID: "live:p1", ORCH_RUN_ID: undefined, ORCH_NODE_ID: undefined, ORCH_NODE_ATTEMPT: undefined };
  const d = orch(home, env as any);
  const instCfg = join(home, "herdr/home/.config/herdr");
  const fakeState = () => { try { return readJson(join(instCfg, "fake/state.json")); } catch { return { workspaces: [], tabs: [], panes: [] }; } };
  const waitJob = (j: string) => d("wait", j, "--timeout", "90", "--interval", "1");
  return { root, home, webdir, log, d, env, instCfg, fakeState, waitJob, realhome, shims, fake, calls: () => readText(log) };
};

test("ensure, status, web env file, health", async () => {
  const t = setup();
  const { d } = t;
  d("init");
  expect(d("herdr", "ensure").rc).toBe(0); expect(d("herdr", "ensure").rc).toBe(0);
  await Promise.all([1, 2, 3].map(() => Bun.spawn(["bash", join(import.meta.dir, "../../scripts/dispatch.sh"), "herdr", "ensure"], { env: { ...process.env, ...t.env, HARNESS_ORCH_HOME: t.home, ORCH_NO_ANNOUNCE: "1" } as any, stdout: "ignore", stderr: "ignore" }).exited));
  expect(readText(join(t.instCfg, "fake/starts")).trim().split("\n").length).toBe(1);
  expect(existsSync(join(t.instCfg, "config.toml"))).toBe(true);
  expect(readText(join(t.instCfg, "config.toml")).split("\n").filter((l) => !l.startsWith("#")).join("\n")).not.toMatch(/plugin|sound|delivery = "(os|all)"/);
  expect(readText(join(t.home, "herdr/server.pid")).trim()).toMatch(/^\d+$/);
  const st = d("herdr", "status").all;
  expect(st).toMatch(/^server: running/m); expect(st).toMatch(/HOME=.*herdr/); expect(st).toMatch(/^herdr: on \(ORCH_HERDR=1\)/m);
  const wf = join(t.webdir, "orch-skill.json");
  expect(existsSync(wf)).toBe(true);
  const env = readJson(wf);
  expect(`${env.id} ${env.label}`).toBe("orch-skill orch-skill");
  expect(env.socket).toMatch(/^\/tmp\/orch-herdr-\d+-\d+\/\.config\/herdr\/herdr\.sock$/);
  expect(env.home).toMatch(/^\/tmp\/orch-herdr-/);
  expect(existsSync(env.socket)).toBe(true);
  expect(readdirSync(t.webdir)).toEqual(["orch-skill.json"]);
  writeFileSync(wf, JSON.stringify({ ...env, socket: "/stale/path.sock" }));
  d("herdr", "ensure");
  expect(readJson(wf).socket).toMatch(/\/herdr\.sock$/);
  expect(t.calls()).not.toMatch(/herdr-web/);

  const hj = (...x: string[]) => JSON.parse(orch(t.home, { ...t.env, ORCH_HERDR_WEB_URL: "off" } as any)("herdr", "health", "--json", ...x).out);
  let h = hj();
  expect([h.state, h.pid_alive, h.socket_ok, h.registry, h.web, h.env_id]).toEqual(["ok", true, true, "ok", "skipped", "orch-skill"]);
  expect(h.registry_path).toBe(wf);
  expect(orch(t.home, { ...t.env, ORCH_HERDR_WEB_URL: "off" } as any)("herdr", "health").all).toMatch(/^herdr health: ok/m);
  Bun.spawnSync(["mv", wf, join(t.root, "wf.moved")]);
  h = hj(); expect([h.state, h.registry]).toEqual(["degraded", "missing"]);
  h = hj("--nudge"); expect([h.state, h.registry, h.nudged]).toEqual(["ok", "ok", true]);
  d("herdr", "stop");
  mkdirSync(t.webdir, { recursive: true });
  writeFileSync(wf, JSON.stringify({ id: "orch-skill", label: "orch-skill", home: "/x", socket: "/x/s" }));
  h = hj(); expect([h.state, h.socket_ok, h.registry]).toEqual(["down", false, "wrong"]);
  expect(h.problems.join(" ")).toMatch(/does not answer/);
  expect(orch(t.home, { ...t.env, ORCH_HERDR_WEB_URL: "off" } as any)("herdr", "health").rc).toBe(3);
  h = hj("--nudge"); expect([h.state, h.socket_ok, h.nudged]).toEqual(["ok", true, true]);
  expect(readText(join(t.instCfg, "fake/starts")).trim().split("\n").length).toBe(2);
  expect(readJson(wf).socket).toMatch(/\/herdr\.sock$/);
  writeFileSync(t.log, "");
  const off = JSON.parse(orch(t.home, { ...t.env, ORCH_HERDR: "0", ORCH_HERDR_WEB_URL: "off" } as any)("herdr", "health", "--json", "--nudge").out);
  expect([off.state, off.enabled]).toEqual(["off", false]);
  expect(t.calls().trim()).toBe("");
  d("herdr", "stop");
  expect(existsSync(wf)).toBe(false);
  d.env({ ORCH_HERDR: "0" }, "herdr", "ensure");
  expect(existsSync(wf)).toBe(false);
  expect(d("herdr", "maybe").rc).toBe(2);
}, 180000);

test("job panes, node tabs, retries, caps, lost panes", async () => {
  const t = setup();
  const { d } = t;
  d("init");
  const job = d.env({ ORCH_HERDR_CLOSE_AFTER: "6", ORCH_TEST_MARKER: "m1" }, "start", "claude", "pane probe").out.trim();
  t.waitJob(job);
  const jd = join(t.home, "jobs", job);
  expect(d("status", job).out.trim()).toBe("done exit=0");
  expect(readText(join(jd, "exit_code")).trim()).toBe("0");
  expect(readText(join(jd, "herdr_pane")).trim()).toBe("w1:p2");
  expect(readText(join(jd, "herdr_sock"))).toMatch(/herdr\.sock$/);
  expect(readText(join(jd, "log"))).toContain(`shim HOME=${t.realhome} marker=m1`);
  expect(readText(join(jd, "herdr-launch.sh"))).not.toMatch(/live-session/);
  expect(readText(join(jd, "herdr-launch.sh"))).toMatch(/exec bun .*\/core\/commands\/herdr-launch\.ts/);
  expect(readText(join(jd, "argv.json"))).toMatch(/"bash","-c"/);
  expect(t.fakeState().tabs.map((x: any) => x.label).join(" ")).toMatch(new RegExp(`(^|\\] )${job}$`));
  expect(t.fakeState().workspaces.map((w: any) => w.label)).toEqual(["jobs"]);
  expect(t.calls()).not.toMatch(/pane split/);
  await waitUntil(() => t.fakeState().tabs.length === 0, 30);
  expect(t.fakeState().tabs.length).toBe(0);

  writeFileSync(t.log, "");
  d("run", "start", "Herdr run", "--id", "hr-run"); d("node", "add", "hr-run", "a", "a");
  const nj = d.env({ ORCH_HERDR_CLOSE_AFTER: "30", ORCH_TEST_EXIT: "3" }, "node", "dispatch", "hr-run", "a", "claude", "fail probe").out.trim();
  t.waitJob(nj);
  expect(d("status", nj).out.trim()).toBe("done exit=3");
  expect(t.fakeState().workspaces.map((w: any) => w.label)).toEqual(["hr-run"]);
  expect(t.fakeState().tabs.map((x: any) => x.label).join(" ")).toMatch(/(^|\] )a$/);
  const tab = t.fakeState().tabs.find((x: any) => /(^|\] )a$/.test(x.label));
  expect(t.fakeState().panes.filter((p: any) => p.tab_id === tab.tab_id).length).toBe(1);
  expect([(t.calls().match(/tab create/g) ?? []).length, (t.calls().match(/pane split/g) ?? []).length]).toEqual([1, 0]);
  expect(readText(join(t.home, "jobs", nj, "herdr_tab")).trim()).toMatch(/^w\d+:t\d+$/);
  writeFileSync(t.log, "");
  const rj = d.env({ ORCH_RUN_ID: "hr-run", ORCH_NODE_ID: "a", ORCH_NODE_ATTEMPT: "2", ORCH_HERDR_CLOSE_AFTER: "30", ORCH_TEST_EXIT: "0" }, "start", "claude", "retry probe").out.trim();
  t.waitJob(rj);
  expect((t.calls().match(/tab create/g) ?? []).length).toBe(0);
  expect(t.fakeState().tabs.map((x: any) => x.label)).toContain("[1] a #2");
  expect(readText(join(t.home, "jobs", rj, "herdr_tab")).trim()).toBe(readText(join(t.home, "jobs", nj, "herdr_tab")).trim());
  expect(t.fakeState().tabs.length).toBe(1);

  for (const tb of t.fakeState().tabs.map((x: any) => x.tab_id)) Bun.spawnSync(["env", "-i", `PATH=${t.env.PATH}`, `HOME=${join(t.home, "herdr/home")}`, "herdr", "tab", "close", tb]);
  const cap2 = d.env({ ORCH_HERDR_PANE_CAP: "2", ORCH_HERDR_CLOSE_AFTER: "30", ORCH_TEST_EXIT: "1" }, "start", "claude", "cap two").out.trim(); t.waitJob(cap2);
  const cap3 = d.env({ ORCH_HERDR_PANE_CAP: "1", ORCH_TEST_EXIT: "1" }, "start", "claude", "cap three").out.trim(); t.waitJob(cap3);
  expect(existsSync(join(t.home, "jobs", cap2, "herdr_pane"))).toBe(true);
  expect(existsSync(join(t.home, "jobs", cap3, "herdr_pane"))).toBe(false);
  expect(d("status", cap3).out.trim()).toBe("done exit=1");

  d("run", "start", "Gone run", "--id", "gone-run"); d("node", "add", "gone-run", "a", "a");
  const gj = d.env({ ORCH_TEST_SLEEP: "60" }, "node", "dispatch", "gone-run", "a", "claude", "die").out.trim();
  await waitUntil(() => existsSync(join(t.home, "jobs", gj, "pid")) && readText(join(t.home, "jobs", gj, "pid")).trim() !== "", 30);
  const gpid = Number(readText(join(t.home, "jobs", gj, "pid")).trim());
  const kids = Bun.spawnSync(["pgrep", "-P", String(gpid)]).stdout.toString().split("\n").filter(Boolean);
  try { process.kill(gpid, "SIGKILL"); } catch {}
  for (const k of kids) try { process.kill(Number(k), "SIGKILL"); } catch {}
  await Bun.sleep(1000);
  d("run", "sync", "gone-run", "--no-retry");
  expect(runState(t.home, "gone-run").nodes[0].status).toBe("error");
  expect(readText(join(t.home, "runs/gone-run/events.jsonl"))).toMatch(/"kind":"note".*"node":"a".*pane w\d+:p\d+ is gone/);
  const bad = t.calls().split("\n").filter((l) => l && !l.includes(`HOME=${join(t.home, "herdr/home")}`) && !l.includes("HOME=/tmp/orch-herdr-")).length;
  expect(bad).toBe(0);
  expect(t.calls()).not.toMatch(/socketenv=.+ ::/);
  expect(t.calls()).not.toMatch(/live-session|realhome/);

  writeFileSync(t.log, "");
  const nopath = pathWithout("herdr");
  const miss = orch(t.home, { ...t.env, PATH: `${t.shims}:${nopath}` })("start", "claude", "missing").out.trim();
  d("wait", miss, "--timeout", "90", "--interval", "1");
  expect(d("status", miss).out.trim()).toBe("done exit=0");
  expect(existsSync(join(t.home, "jobs", miss, "herdr_pane"))).toBe(false);
  expect(orch(t.home, { ...t.env, PATH: `${t.shims}:${nopath}` })("herdr", "status").all).toMatch(/herdr not on PATH/);
  const off = d.env({ ORCH_HERDR: "0" }, "start", "claude", "off").out.trim(); t.waitJob(off);
  expect(existsSync(join(t.home, "jobs", off, "herdr_pane"))).toBe(false);
  d("herdr", "stop");
  const down = d.env({ ORCH_HERDR_FAKE_DOWN: "1" }, "start", "claude", "unreachable").out.trim(); t.waitJob(down);
  expect(d("status", down).out.trim()).toBe("done exit=0");
  expect(existsSync(join(t.home, "jobs", down, "herdr_pane"))).toBe(false);
  d("herdr", "stop");
}, 300000);
