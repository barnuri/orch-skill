import { test, expect } from "bun:test";
import { join } from "node:path";
import { mkdirSync, writeFileSync, existsSync, statSync, readdirSync, readFileSync } from "node:fs";
import { orch, seedHome, tempDir, fakeBin, readJson, readText, runCmd, DISPATCH, ORCH_DIR, cleanEnv, waitUntil, pidAlive, autoCleanup } from "../helpers";
autoCleanup();

// The announcer is driven through its dispatch subcommand (`dispatch.sh announce`) with a fake herdr.
const mk = (herdrTail = "exit 0", agent = "opencode") => {
  const T = tempDir(), H = join(T, "home"), O = join(T, "orch");
  mkdirSync(H, { recursive: true }); mkdirSync(O, { recursive: true });
  const calls = join(T, "calls"); writeFileSync(calls, "");
  const fake = fakeBin({ herdr: `printf "%s\\n" "$*" >> "${calls}"\nif [ "$1 $2" = "pane current" ]; then echo '{"result":{"pane":{"agent":"${agent}"}}}'; fi\n${herdrTail}` });
  const env = { HOME: H, HARNESS_ORCH_HOME: O, HERDR_ENV: "1", HERDR_PANE_ID: "p1", HERDR_BIN_PATH: join(fake, "herdr"), CLAUDE_CODE_SESSION_ID: "sess1", ANNOUNCE_NO_DAEMON: "1", ORCH_NO_ANNOUNCE: undefined as any };
  const ann = (...a: string[]) => runCmd(["bun", DISPATCH, "announce", ...a], { env });
  return { T, H, O, calls, fake, env, ann, callsText: () => readText(calls) };
};
const seedRun = (O: string) => { mkdirSync(join(O, "runs/r1"), { recursive: true }); writeFileSync(join(O, "runs/r1/state.json"), JSON.stringify({ run_id: "r1", status: "running", nodes: [{ id: "a", status: "done" }, { id: "b", status: "running" }, { id: "c", status: "running" }, { id: "d", status: "waiting" }] })); };
const seedState = (O: string, dir: string, name: string, status: string, pid: number) => { mkdirSync(join(O, dir, name), { recursive: true }); writeFileSync(join(O, dir, name, "state.json"), JSON.stringify({ status, pid })); };

test("announce: idle, counts, filters, no-ops", () => {
  let t = mk();
  expect(t.ann("--quiet").rc).toBe(0);
  expect(readText(join(t.O, "activity/sess1.json"))).toMatch(/"active":false/);
  expect(t.callsText()).toMatch(/clear-state-labels.*clear-token orch/);
  expect(readText(join(t.H, ".claude/workflow-active/sess1"))).toMatch(/"active":false/);

  t = mk(); seedRun(t.O);
  const live = Bun.spawn(["sleep", "900"]);
  seedState(t.O, "loops", "l1", "running", live.pid); seedState(t.O, "loops", "l2", "running", 999999);
  seedState(t.O, "watches", "w1", "running", live.pid); seedState(t.O, "watches", "w2", "running", live.pid);
  t.ann("--quiet", "--ttl-sec", "45");
  const j = readText(join(t.O, "activity/sess1.json"));
  expect(j).toMatch(/"running":2,"done":1,"total":4/);
  expect(j).toMatch(/orch: 2 running, 1\/4 done · 1 loop · 2 monitors/);
  expect(JSON.parse(j).summary).not.toContain("loops");
  const c = t.callsText();
  expect(c).toMatch(/ttl-ms 45000/); expect(c).toMatch(/--agent opencode/); expect(c).toMatch(/--source user:orch/);
  expect((c.match(/report-agent/g) ?? []).length).toBe(0);
  expect((statSync(join(t.O, "activity/sess1.json")).mode & 0o777).toString(8)).toBe("600");
  expect(readdirSync(join(t.O, "activity")).filter((f) => f.startsWith(".tmp")).length).toBe(0);
  expect(readText(join(t.H, ".claude/workflow-active/sess1"))).toMatch(/"active":true/);
  live.kill();

  t = mk(); seedRun(t.O); t.ann("--quiet", "--run", "nope");
  expect(readText(join(t.O, "activity/sess1.json"))).toMatch(/"active":false/);
  t = mk(); seedRun(t.O);
  runCmd(["bun", DISPATCH, "announce", "--quiet"], { env: { ...t.env, HERDR_ENV: undefined, HERDR_PANE_ID: undefined, CLAUDE_CODE_SESSION_ID: "s" } });
  expect(t.callsText().trim()).toBe("");
  t = mk("exit 3"); seedRun(t.O); expect(t.ann("--quiet").rc).toBe(0);
  t = mk("exec sleep 20"); seedRun(t.O);
  const s = Date.now();
  const r = runCmd(["bun", DISPATCH, "announce", "--quiet"], { env: { ...t.env, ANNOUNCE_HERDR_TIMEOUT: "1" } });
  expect(r.rc).toBe(0); expect((Date.now() - s) / 1000).toBeLessThan(30);
  t = mk(); seedRun(t.O);
  const d = t.ann("--dry-run").out;
  expect(d).toMatch(/report-metadata p1 .*--ttl-ms 120000/); expect(d).toMatch(/file: .*activity\/sess1.json/);
  expect((t.callsText().match(/report-metadata/g) ?? []).length).toBe(0);
  expect(existsSync(join(t.O, "activity"))).toBe(false);
  expect(t.ann("--dry-run", "--quiet").out).toBe("");
  t = mk(); mkdirSync(join(t.O, "runs/big"), { recursive: true });
  writeFileSync(join(t.O, "runs/big/state.json"), JSON.stringify({ status: "running", nodes: Array.from({ length: 500 }, (_, i) => ({ id: `n${i}`, status: "running" })) }));
  t.ann("--quiet");
  expect(readJson(join(t.O, "activity/sess1.json")).summary.length).toBeLessThan(1000);
  t = mk();
  const o = orch(t.O); o("init");
  const R = o("run", "start", "real").out.trim();
  o("node", "add", R, "a", "A"); o("node", "add", R, "b", "B"); o("node", "update", R, "a", "running"); o("node", "update", R, "a", "done"); o("node", "update", R, "b", "running");
  t.ann("--quiet", "--run", R);
  expect(readText(join(t.O, "activity/sess1.json"))).toMatch(/orch: 1 running, 1\/2 done/);
  t = mk(); seedRun(t.O); t.ann("--quiet", "--clear");
  expect(readText(join(t.O, "activity/sess1.json"))).toMatch(/"active":false/);
  t = mk();
  const lp = Bun.spawn(["sleep", "900"]);
  seedState(t.O, "loops", "live", "running", lp.pid);
  for (const st of ["stopped", "done", "failed"]) seedState(t.O, "loops", st, st, lp.pid);
  seedState(t.O, "loops", "dead", "running", 999999);
  t.ann("--quiet");
  expect(readJson(join(t.O, "activity/sess1.json")).summary).toBe("orch: 0 running, 0/0 done · 1 loop");
  lp.kill();
}, 120000);

test("announce hook from dispatch and daemon", async () => {
  const t = mk();
  const base = { ...t.env, ANNOUNCE_NO_DAEMON: undefined as any };
  const hk = (...a: string[]) => runCmd(["bun", DISPATCH, ...a], { env: { ...base } });
  runCmd(["bun", DISPATCH, "init"], { env: { ...base, ORCH_NO_ANNOUNCE: "1" } });
  const R = hk("run", "start", "hook").out.trim();
  await waitUntil(() => t.callsText().includes("report-metadata"), 10);
  expect(t.callsText()).toMatch(/report-metadata p1/);
  hk("node", "add", R, "a", "A"); await Bun.sleep(1000); writeFileSync(t.calls, "");
  writeFileSync(join(t.O, ".announce-ts"), `${Math.floor(Date.now() / 1000) + 60}\n`);
  expect(hk("node", "update", R, "a", "running").rc).toBe(0);
  await Bun.sleep(1000);
  expect((t.callsText().match(/report-metadata/g) ?? []).length).toBe(0);
  writeFileSync(join(t.O, ".announce-ts"), `${Math.floor(Date.now() / 1000) - 10}\n`);
  hk("node", "ping", R, "a", "--note", "x");
  await waitUntil(() => t.callsText().includes("report-metadata"), 10);
  expect(t.callsText()).toMatch(/orch: 1 running/);
  writeFileSync(t.calls, ""); writeFileSync(join(t.O, ".announce-ts"), "0\n");
  runCmd(["bun", DISPATCH, "node", "ping", R, "a", "--note", "y"], { env: { ...base, ORCH_NO_ANNOUNCE: "1" } });
  await Bun.sleep(1500);
  expect((t.callsText().match(/report-metadata/g) ?? []).length).toBe(0);
  runCmd(["bun", DISPATCH, "node", "ping", R, "a", "--note", "z"], { env: { ...base, HERDR_ENV: undefined, HERDR_PANE_ID: undefined, CLAUDE_CODE_SESSION_ID: undefined, OPENCODE_SESSION_ID: undefined } });
  await Bun.sleep(1500);
  expect((t.callsText().match(/report-metadata/g) ?? []).length).toBe(0);
  expect(runCmd(["bun", DISPATCH, "announce", "--dry-run"], { env: { ...base } }).out).toMatch(/orch: 1 running/);
}, 120000);

test("announce daemon, sync lock, harness list lock", async () => {
  const t = mk();
  const fake = fakeBin({ herdr: `if [ "$1 $2" = "pane current" ]; then echo '{"result":{"pane":{"agent":"claude"}}}'; exit 0; fi\necho "$@" >> "${t.calls}"` });
  const env = { ...t.env, HERDR_BIN_PATH: join(fake, "herdr"), ANNOUNCE_NO_DAEMON: undefined as any, ANNOUNCE_INTERVAL: "1", ANNOUNCE_IDLE_SECS: "3", ANNOUNCE_SID: "sess1", ANNOUNCE_HARNESS: "claude", ORCH_NO_ANNOUNCE: "1" };
  const o = orch(t.O, { ...env });
  const ann = (...a: string[]) => runCmd(["bun", DISPATCH, "announce", ...a], { env });
  const R = o("run", "start", "daemon demo").out.trim();
  o("node", "add", R, "a", "a"); o("node", "update", R, "a", "running", "--owner", "coordinator");
  const act = join(t.O, "activity/sess1.json"), pidf = join(t.O, "announce.pid");
  ann("--quiet");
  await waitUntil(() => { try { return readJson(act).pane === "p1" && pidAlive(Number(readText(pidf))); } catch { return false; } }, 15);
  expect(readJson(act).pane).toBe("p1");
  const pid = Number(readText(pidf));
  expect(pidAlive(pid)).toBe(true);
  const upd = () => { try { return readJson(act).updated_at as number; } catch { return 0; } };
  const u1 = upd(); await waitUntil(() => upd() > u1, 15); const u2 = upd();
  expect(u2).toBeGreaterThan(u1);
  await waitUntil(() => upd() > u2, 15); expect(upd()).toBeGreaterThan(u2);
  await waitUntil(() => (t.callsText().match(/report-metadata/g) ?? []).length >= 3, 15);
  expect((t.callsText().match(/report-metadata/g) ?? []).length).toBeGreaterThanOrEqual(3);
  ann("--quiet"); ann("--quiet"); await Bun.sleep(2000);
  expect((readText(join(t.O, "announce.log")).match(/started/g) ?? []).length).toBe(1);
  expect(Number(readText(pidf))).toBe(pid);
  ann("--clear", "--quiet"); await waitUntil(() => !pidAlive(pid), 15);
  expect(pidAlive(pid)).toBe(false);
  writeFileSync(pidf, "999999\n"); ann("--quiet");
  await waitUntil(() => { const n = Number(readText(pidf)); return n !== 999999 && pidAlive(n); }, 15);
  const npid = Number(readText(pidf));
  expect(npid !== 999999 && pidAlive(npid)).toBe(true);
  o("node", "update", R, "a", "done", "--force"); o("run", "finish", R);
  await waitUntil(() => !pidAlive(npid), 30);
  expect(pidAlive(npid)).toBe(false);
  expect(readText(join(t.O, "announce.log"))).toMatch(/idle, exiting/);
  writeFileSync(join(t.O, "announce.log"), "x".repeat(200000)); writeFileSync(pidf, "999999\n");
  const R2 = o("run", "start", "log cap").out.trim(); o("node", "add", R2, "a", "a"); o("node", "update", R2, "a", "running", "--owner", "coordinator");
  ann("--quiet");
  await waitUntil(() => Number(readText(pidf)) !== 999999 && statSync(join(t.O, "announce.log")).size < 160000, 15);
  expect(statSync(join(t.O, "announce.log")).size).toBeLessThan(160000);
  ann("--clear", "--quiet"); await Bun.sleep(1000);
  mkdirSync(join(t.O, "locks"), { recursive: true });
  const holder = Bun.spawn(["sleep", "20"]);
  writeFileSync(join(t.O, "locks", `sync-${R}.pid`), `${holder.pid}\n`);
  expect(o("run", "sync", R, "--lock").all).toMatch(/still running, skipped/);
  holder.kill(); await holder.exited;
  expect(o("run", "sync", R, "--lock").out).toMatch(/^running: /m);
  expect(readText(join(t.O, "locks", `sync-${R}.pid`))).toBe("");
  const h2 = Bun.spawn(["sleep", "20"]);
  writeFileSync(join(t.O, "locks/harness-list.pid"), `${h2.pid}\n`);
  writeFileSync(join(t.O, "locks/harness-list.last"), '{"cached":true}\n');
  expect(o("harness", "list", "--json").out.trim()).toBe('{"cached":true}');
  h2.kill(); ann("--clear", "--quiet");
}, 240000);
