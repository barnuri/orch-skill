import { test, expect } from "bun:test";
import { join } from "node:path";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { orch, seedHome, tempDir, fakeBin, editJson, readJson, readText, REPO_ROOT, ORCH_DIR, runCmd, waitUntil, listFiles, autoCleanup } from "../helpers";
autoCleanup();

test("the skill folder holds no dashboard code", () => {
  const stray = Bun.spawnSync(["sh", "-c", `find "${ORCH_DIR}" -type f \\( -name '*.tsx' -o -name '*.css' -o -name '*.html' \\) -not -path '*/node_modules/*' -not -path '*/tests/*' | head -3`]).stdout.toString().trim();
  expect(stray).toBe("");
  expect(existsSync(join(REPO_ROOT, "src/server/main.ts"))).toBe(true);
  expect(existsSync(join(ORCH_DIR, "server"))).toBe(false);
});

test("disabled harness refuses profile runs", () => {
  const home = seedHome();
  const sh = fakeBin({ claude: 'printf "ran\\n"' });
  const o = orch(home, { PATH: `${sh}:${process.env.PATH}` });
  expect(o("run", "--profile", "claude-default", "hi").rc).toBe(0);
  editJson(join(home, "profiles.json"), (p) => { p.settings.disabled_harnesses = ["claude"]; });
  let r = o("run", "--profile", "claude-default", "hi");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/harness "claude" is disabled.*Harnesses page/);
  expect(o("start", "--profile", "claude-default", "hi").rc).toBe(2);
  expect(o("profile", "sanity", "--profile", "claude-default").all).toMatch(/"status":"disabled".*"error":"harness disabled"/);
  editJson(join(home, "profiles.json"), (p) => { p.settings.disabled_harnesses = []; });
  expect(o("run", "--profile", "claude-default", "hi").rc).toBe(0);
});

test("schedules", async () => {
  const home = seedHome();
  const argvFile = join(home, "claude-argv");
  const sh = fakeBin({ claude: `printf "%s\\n" "$@" > "${argvFile}"` });
  const o = orch(home, { PATH: `${sh}:${process.env.PATH}` });
  const sch = (...a: string[]) => o("schedule", ...a);
  const show = (id: string) => JSON.parse(sch("show", id).out);
  const finish = async (id: string, secs = 10) => { await waitUntil(() => show(id).runs[0]?.status !== "running", secs); };
  let r = sch("next", "0 9 * * 1-5");
  expect(r.rc).toBe(0); expect(r.out).toMatch(/ 09:00$/m);
  for (const bad of ["61 * * * *", "* * *", "0 0 31 2 *", "x * * * *"]) expect(sch("next", bad).rc).toBe(2);
  expect(sch("add", "--name", "n", "--cron", "* * * * *").rc).toBe(2);
  expect(sch("add", "--name", "n", "--cron", "* * * * *", "--prompt", "hi").rc).toBe(2);
  expect(sch("add", "--name", "n", "--cron", "* * * * *", "--prompt", "hi", "--command", "true", "--profile", "claude-default").rc).toBe(2);
  const cmdId = sch("add", "--name", "echoer", "--cron", "* * * * *", "--command", "echo from-schedule").out.trim();
  expect(cmdId).toMatch(/^sch-\d{8}-\d{6}-[0-9a-f]{4}$/);
  sch("run", cmdId); await finish(cmdId);
  expect(show(cmdId).runs[0].status).toBe("ok");
  const run0 = show(cmdId).runs[0];
  expect((Date.parse(run0.ended_at) - Date.parse(run0.started_at)) / 1000).toBeLessThanOrEqual(1);
  const runsDir = join(home, "schedules", cmdId, "runs");
  expect(listFiles(runsDir).map((d) => readText(join(runsDir, d, "out"))).join("")).toMatch(/from-schedule/);
  const dueFile = join(home, "schedules", cmdId, "schedule.json");
  editJson(dueFile, (s) => { s.next_at = 1; });
  expect(sch("tick").all).toContain(`fired: ${cmdId}`);
  expect(readJson(dueFile).next_at).toBeGreaterThan(Date.now() / 1000);
  expect(sch("tick").all).not.toMatch(/fired:/);
  const slow = sch("add", "--name", "slow", "--cron", "* * * * *", "--command", "sleep 60", "--timeout", "5s").out.trim();
  sch("run", slow);
  editJson(join(home, "schedules", slow, "schedule.json"), (s) => { s.next_at = 1; });
  expect(sch("tick").all).toMatch(new RegExp(`skipped \\(still running\\): ${slow}`));
  sch("remove", slow);
  const kill = sch("add", "--name", "timeout", "--cron", "* * * * *", "--command", "sleep 60", "--timeout", "2s").out.trim();
  sch("run", kill); await finish(kill, 60);
  expect([show(kill).runs[0].status, show(kill).runs[0].exit]).toEqual(["failed", 142]);
  sch("remove", kill);
  sch("disable", cmdId);
  expect(readJson(dueFile).next_at).toBeNull();
  editJson(dueFile, (s) => { s.next_at = 1; });
  expect(sch("tick").all).not.toContain(`fired: ${cmdId}`);
  sch("enable", cmdId);
  expect(readJson(dueFile).next_at).toBeGreaterThan(Date.now() / 1000);
  const promptId = sch("add", "--name", "prompter", "--cron", "* * * * *", "--prompt", "say hi", "--profile", "claude-default").out.trim();
  expect(promptId).toMatch(/^sch-/);
  expect(sch("run", promptId).rc).toBe(0); await finish(promptId);
  expect(readText(argvFile)).toMatch(/say hi/);
  expect(show(promptId).runs[0].status).toBe("ok");
  expect(show(promptId).runs[0].model ?? null).toBeNull();
  const argvLines = () => readText(argvFile).split("\n");
  expect(argvLines()[argvLines().indexOf("--model") + 1]).toBe("sonnet");
  editJson(join(home, "profiles.json"), (p) => { p.profiles["claude-default"].allowed_models = ["claude-sonnet", "claude-opus"]; });
  r = sch("add", "--name", "m", "--cron", "* * * * *", "--prompt", "hi", "--profile", "claude-default", "--model", "claude-haiku");
  expect(r.rc).toBe(2); expect(r.all).toMatch(/claude-haiku is not allowed/);
  expect(sch("add", "--name", "m", "--cron", "* * * * *", "--command", "true", "--model", "claude-opus").rc).toBe(2);
  const modelId = sch("add", "--name", "modeled", "--cron", "0 9 * * *", "--prompt", "use opus", "--profile", "claude-default", "--model", "claude-opus").out.trim();
  expect(modelId).toMatch(/^sch-/);
  expect(show(modelId).model).toBe("claude-opus");
  expect(show(promptId).model ?? null).toBeNull();
  writeFileSync(argvFile, "");
  expect(sch("run", modelId).rc).toBe(0); await finish(modelId);
  expect(argvLines()[argvLines().indexOf("--model") + 1]).toBe("opus");
  expect(show(modelId).runs[0].model).toBe("claude-opus");
  expect(readText(join(home, "jobs", show(modelId).runs[0].ref, "model")).trim()).toBe("opus");
  sch("remove", modelId);
  expect(JSON.parse(sch("list", "--json").out).length).toBe(2);
  expect(sch("show", kill).rc).toBe(2);
}, 240000);
